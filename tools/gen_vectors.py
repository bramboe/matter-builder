#!/usr/bin/env python3
"""Generate golden test vectors for the C++ protocol port.

Runs the reference Python implementation from the octo-bed Home Assistant
integration and writes test/host/vectors.inc. The generated file is committed,
so the host tests run without the octo-bed checkout.

Usage: tools/gen_vectors.py [path/to/octo-bed]   (default: ../octo-bed)
"""

from __future__ import annotations

import importlib.util
import random
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "test" / "host" / "vectors.inc"


def load_reference(octo_bed: Path) -> tuple[types.ModuleType, types.ModuleType]:
    """Load protocol.py and const.py without importing Home Assistant."""
    src = octo_bed / "custom_components" / "octo_bed"
    spec = importlib.util.spec_from_file_location("octo_protocol_ref", src / "protocol.py")
    protocol = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(protocol)

    const = types.ModuleType("octo_const_ref")
    const.protocol = protocol
    source = (src / "const.py").read_text().replace("from . import protocol", "")
    exec(compile(source, str(src / "const.py"), "exec"), const.__dict__)
    return protocol, const


def arr(data: bytes | list[int]) -> str:
    return "{" + ", ".join(f"0x{b:02x}" for b in data) + "}"


def main() -> None:
    octo_bed = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "octo-bed"
    protocol, const = load_reference(octo_bed)
    rng = random.Random(0x0C70)
    escaped = [0x40, 0x3C, 0x4F, 0x41]
    commands = [
        value
        for name, value in vars(protocol).items()
        if name.startswith("CMD_") and isinstance(value, tuple)
    ]

    build: list[tuple[tuple[int, int], list[int]]] = []
    for command in commands:
        build.append((command, []))
        build.append((command, [protocol.MOTOR_BOTH]))
    for _ in range(200):
        command = rng.choice(commands + [(0x40, 0x3C), (0x4F, 0x41)])
        length = rng.randint(0, 24)
        data = [rng.choice(escaped) if rng.random() < 0.3 else rng.randrange(256) for _ in range(length)]
        build.append((command, data))

    parse_inputs: list[bytes] = [
        const.NOTIFY_PIN_REQUIRED,
        const.NOTIFY_PIN_REQUIRED_ALT,
        const.NOTIFY_PIN_ACCEPTED,
        const.NOTIFY_PIN_REJECTED,
        bytes([0x40, 0x3C, 0x40]),
        bytes([0x40, 0x21, 0x71, 0x00, 0x01, 0x00, 0x3C, 0x40]),  # dangling escape
        bytes([0x40, 0x21, 0x71, 0x00, 0x01, 0x00, 0x3C, 0x09, 0x40]),  # unknown escape
        bytes([0x41, 0x21, 0x71, 0x00, 0x00, 0x00, 0x40]),
    ]
    for command, data in build[:120]:
        packet = protocol.build_packet(command, data)
        parse_inputs.append(packet)
        # Responses: same layout, 0x80-based checksum
        unescaped = [0x80, command[0], command[1], len(data) >> 8, len(data) & 0xFF, *data]
        checksum = protocol.calculate_checksum(unescaped)
        payload = protocol._escape([command[0], command[1], len(data) >> 8, len(data) & 0xFF, checksum, *data])
        parse_inputs.append(bytes([0x40, *payload, 0x40]))
        mutated = bytearray(packet)
        mutated[rng.randrange(len(mutated))] = rng.randrange(256)
        parse_inputs.append(bytes(mutated))
        parse_inputs.append(packet[: rng.randrange(len(packet))])

    features: list[list[int]] = [
        [0x00, 0x00, 0x01, 0x00, 0x00, 0x01, 0x02],
        [0x00, 0x00, 0x02, 0x00, 0x00, 0x01, 0x03],
        [0x00, 0x01, 0x04, 0x00, 0x02, 0xAA, 0xBB, 0x05, 0x01, 0x02, 0x03, 0x04],
        [0xFF, 0xFF, 0xFF, 0x00, 0x00, 0x00],
        [0x00, 0x01, 0x02, 0x00, 0x09, 0x00],
        [0x00, 0x01, 0x02, 0x00, 0x00],
    ]
    for _ in range(60):
        features.append([rng.randrange(256) for _ in range(rng.randint(0, 14))])

    pins = ["1234", "0000", "9999", "4040", "123", "12345", "12a4", "", " 123"]

    named = {
        "HEAD_UP": const.CMD_HEAD_UP,
        "HEAD_DOWN": const.CMD_HEAD_DOWN,
        "FEET_UP": const.CMD_FEET_UP,
        "FEET_DOWN": const.CMD_FEET_DOWN,
        "BOTH_UP": const.CMD_BOTH_UP,
        "BOTH_DOWN": const.CMD_BOTH_DOWN,
        "STOP": const.CMD_STOP,
        "LIGHT_ON": const.CMD_LIGHT_ON,
        "LIGHT_OFF": const.CMD_LIGHT_OFF,
        "GET_FEATURES": protocol.build_packet(protocol.CMD_SYSTEM_GET_CAPS),
        "RGBW_10_20_30_40": protocol.build_packet(
            protocol.CMD_SYSTEM_SET_CAPS,
            [0x00, 0x01, 0x04, 0x00, 0x01, 0x01, 0x05, 10, 20, 30, 40, 0xFF],
        ),
        "RGBW_40_3C_4F_41_T6": protocol.build_packet(
            protocol.CMD_SYSTEM_SET_CAPS,
            [0x00, 0x01, 0x04, 0x00, 0x01, 0x01, 0x06, 0x40, 0x3C, 0x4F, 0x41, 0xFF],
        ),
    }

    lines = [
        "// Generated by tools/gen_vectors.py from the octo-bed Python protocol. Do not edit.",
        "",
        "static const BuildVector BUILD_VECTORS[] = {",
    ]
    for command, data in build:
        lines.append(
            f"    {{{{0x{command[0]:02x}, 0x{command[1]:02x}}}, {arr(data)}, "
            f"{arr(protocol.build_packet(command, data))}}},"
        )
    lines += ["};", "", "static const ParseVector PARSE_VECTORS[] = {"]
    for message in parse_inputs:
        parsed = protocol.parse_packet(message)
        ok = parsed is not None
        command, data = parsed if ok else ((0, 0), [])
        lines.append(
            f"    {{{arr(message)}, {str(ok).lower()}, {{0x{command[0]:02x}, 0x{command[1]:02x}}}, "
            f"{arr(data)}, {str(protocol.verify_response_checksum(message)).lower()}}},"
        )
    lines += ["};", "", "static const FeatureVector FEATURE_VECTORS[] = {"]
    for data in features:
        result = protocol.extract_feature(data)
        ok = result is not None
        feature_id, value, value_type = result if ok else (0, [], None)
        lines.append(
            f"    {{{arr(data)}, {str(ok).lower()}, 0x{feature_id:06x}, {arr(value)}, "
            f"{-1 if value_type is None else value_type}}},"
        )
    lines += ["};", "", "static const PinVector PIN_VECTORS[] = {"]
    for pin in pins:
        try:
            expected, ok = protocol.encode_pin(pin), True
        except ValueError:
            expected, ok = b"", False
        lines.append(f'    {{"{pin}", {str(ok).lower()}, {arr(expected)}}},')
    lines += ["};", "", "static const NamedVector NAMED_VECTORS[] = {"]
    for name, packet in named.items():
        lines.append(f'    {{"{name}", {arr(packet)}}},')
    lines += ["};", ""]

    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(build)} build, {len(parse_inputs)} parse, "
          f"{len(features)} feature, {len(pins)} pin, {len(named)} named vectors")


if __name__ == "__main__":
    main()
